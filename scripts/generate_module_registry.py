import json
from pathlib import Path
import argparse

parser = argparse.ArgumentParser()
parser.add_argument("--output", default="GeneratedModules.cpp", help="Output .cpp file path")
parser.add_argument("--module-json", action="append", default=[], help="Path to a module.json (repeatable)")
args = parser.parse_args()

output_file = Path(args.output)
modules = []

json_paths = [Path(p).resolve() for p in args.module_json]

for mod_json in json_paths:
    data = json.loads(mod_json.read_text(encoding="utf-8"))

    # only fabric modules (must have class/include)
    if "class" not in data or "include" not in data:
        continue

    fq_class = data["class"]
    include = str(data["include"]).replace("\\", "/")
    modules.append((include, fq_class))

with output_file.open("w", encoding="utf-8") as out:
    out.write("// Auto-generated by Rhea/scripts/generate_module_registry.py\n")
    out.write("#include <memory>\n")
    out.write("#include <vector>\n")
    out.write("#include <Rhea/Application.h>\n\n")

    for include, _ in modules:
        out.write(f'#include <{include}>\n')

    out.write("\nstd::vector<std::unique_ptr<Rhea::IFabricModule>> createModules() {\n")
    out.write("    std::vector<std::unique_ptr<Rhea::IFabricModule>> modules;\n\n")

    for _, fq_class in modules:
        out.write(f"    modules.push_back(std::make_unique<{fq_class}>());\n")

    out.write("\n    return modules;\n")
    out.write("}\n")

print(f"[OK] Generated {output_file}")
