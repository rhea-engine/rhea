#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any


def fail(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def info(msg: str) -> None:
    print(msg)


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def find_project_root(start: Path) -> Path:
    current = start.resolve()
    while True:
        if (current / "CMakeLists.txt").exists():
            return current
        if current.parent == current:
            fail("could not find project root (missing CMakeLists.txt)")
        current = current.parent


def detect_vendor_and_project(root: Path) -> tuple[str, str]:
    include_dir = root / "include"
    if not include_dir.exists():
        fail("missing include/ directory; run this inside a project created by mwpkg init")

    vendors = [p for p in include_dir.iterdir() if p.is_dir()]
    if len(vendors) != 1:
        fail("could not determine vendor from include/ (expected exactly one vendor directory)")

    vendor_dir = vendors[0]
    vendor = vendor_dir.name

    projects = [p for p in vendor_dir.iterdir() if p.is_dir()]
    if len(projects) != 1:
        fail("could not determine project name from include/<Vendor>/ (expected exactly one project directory)")

    project = projects[0].name
    return vendor, project


def render_text(template_text: str, values: dict[str, str]) -> str:
    result = template_text
    for key, value in values.items():
        result = result.replace(f"{{{{{key}}}}}", value)
    return result


def render_path(path_template: str, values: dict[str, str]) -> Path:
    return Path(render_text(path_template, values))


def load_json(path: Path) -> dict[str, Any]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception as e:
        fail(f"failed to parse json file {path}: {e}")
        raise


def load_template_definition(template_dir: Path) -> dict[str, Any]:
    template_json = template_dir / "template.json"
    if not template_json.exists():
        fail(f"missing template definition: {template_json}")
    return load_json(template_json)


def detect_installed_packages_from_mwpkg(root: Path) -> set[str]:
    mwpkg_cmake = root / "mwpkg.cmake"
    if not mwpkg_cmake.exists():
        return set()

    text = mwpkg_cmake.read_text(encoding="utf-8")
    pattern = re.compile(r'add_subdirectory\("MwpkgModules/([^/"]+)/([^/"]+)"\)')
    packages: set[str] = set()

    for match in pattern.finditer(text):
        vendor, package = match.groups()
        packages.add(f"{vendor}/{package}")

    return packages

def looks_like_default_mwpkg_cmakelists(text: str, project: str) -> bool:
    return (
        f"add_library({project})" in text
        and f"src/{project}.cpp" in text
        and "rhea_project.cmake" not in text
    )


def looks_like_generated_rhea_cmakelists(text: str) -> bool:
    return "Generated by rhea init" in text or "rhea_project.cmake" in text


def looks_like_default_project_cpp(text: str, vendor: str, project: str) -> bool:
    stripped = text.strip()
    expected_include = f'#include <{vendor}/{project}/{project}.h>'

    if stripped == expected_include:
        return True

    if "Generated by rhea init" in stripped:
        return True

    # Very small placeholder source file
    nonempty_lines = [line.strip() for line in text.splitlines() if line.strip()]
    if len(nonempty_lines) <= 3 and any(expected_include in line for line in nonempty_lines):
        return True

    return False


def looks_like_generated_enabled_json(text: str) -> bool:
    stripped = text.strip()
    if not stripped:
        return True
    if stripped == "{}":
        return True
    if '"enabled_fabrics"' in stripped and "_generated_by" in stripped:
        return True
    return False


def is_safe_to_overwrite(path: Path, force: bool, vendor: str, project: str) -> bool:
    if force:
        return True

    if not path.exists():
        return True

    text = path.read_text(encoding="utf-8")

    if path.name == "CMakeLists.txt":
        return looks_like_default_mwpkg_cmakelists(text, project) or looks_like_generated_rhea_cmakelists(text)

    if path.name == f"{project}.cpp":
        return looks_like_default_project_cpp(text, vendor, project)

    if path.name == "enabled.json":
        return looks_like_generated_enabled_json(text)

    if path.name == ".gitkeep":
        return True

    # Default: do not overwrite unknown existing files unless --force
    return False

def run_command(cmd: list[str], cwd: Path) -> None:
    info("running: " + " ".join(cmd))
    result = subprocess.run(cmd, cwd=str(cwd))
    if result.returncode != 0:
        fail(f"command failed with exit code {result.returncode}: {' '.join(cmd)}")


def ensure_packages_installed(root: Path, packages: list[str], use_link: bool = False) -> None:
    installed = detect_installed_packages_from_mwpkg(root)

    for package in packages:
        if package in installed:
            info(f"package already installed: {package}")
            continue

        cmd = ["mwpkg", "install"]
        if use_link:
            cmd.append("--link")
        cmd.append(package)
        run_command(cmd, root)


def resolve_template_requirements(template_data: dict[str, Any], enabled_features: set[str]) -> tuple[list[str], list[str]]:
    packages = list(template_data.get("required_packages", []))
    fabrics = list(template_data.get("default_enabled_fabrics", []))

    features = template_data.get("features", {})
    for feature_name in enabled_features:
        feature = features.get(feature_name)
        if not feature:
            fail(f"unknown feature '{feature_name}' for template '{template_data.get('name', '<unknown>')}'")
        packages.extend(feature.get("packages", []))
        fabrics.extend(feature.get("enabled_fabrics", []))

    # stable unique order
    packages = list(dict.fromkeys(packages))
    fabrics = list(dict.fromkeys(fabrics))
    return packages, fabrics


def check_overwrite_allowed(path: Path, force: bool, vendor, project) -> None:
    if not is_safe_to_overwrite(path, force, vendor, project):
        fail(f"{path} already exists and appears user-modified; use --force to overwrite")


def copy_or_render_template_file(
    src: Path,
    dst: Path,
    values: dict[str, str],
    enabled_fabrics: list[str],
    force: bool,
    vendor: str,
    project: str,
) -> None:
    check_overwrite_allowed(dst, force, vendor, project)

    ensure_dir(dst.parent)

    if src.suffix == ".in":
        if src.name == "enabled.json.in":
            rendered = json.dumps(
                {
                    "_generated_by": "rhea init",
                    "enabled_fabrics": enabled_fabrics,
                },
                indent=2,
            ) + "\n"
        else:
            text = src.read_text(encoding="utf-8")
            rendered = render_text(text, values)

            # Add a generated marker comment for known text files
            if dst.suffix in {".cpp", ".h", ".hpp", ".cmake", ".txt"} or dst.name == "CMakeLists.txt":
                rendered = f"# Generated by rhea init\n\n{rendered}" if dst.name == "CMakeLists.txt" else f"// Generated by rhea init\n\n{rendered}"

        dst.write_text(rendered, encoding="utf-8")
    else:
        shutil.copyfile(src, dst)

    info(f"wrote {dst}")


def write_template_files(
    root: Path,
    template_dir: Path,
    template_data: dict[str, Any],
    values: dict[str, str],
    enabled_fabrics: list[str],
    force: bool,
) -> None:
    files = template_data.get("files", [])
    if not files:
        fail(f"template '{template_data.get('name', '<unknown>')}' defines no files")

    for file_entry in files:
        if "template" not in file_entry or "output" not in file_entry:
            fail("each template file entry must contain 'template' and 'output'")

        src = template_dir / file_entry["template"]
        if not src.exists():
            fail(f"missing template file: {src}")

        dst = root / render_path(file_entry["output"], values)
        copy_or_render_template_file(
            src=src,
            dst=dst,
            values=values,
            enabled_fabrics=enabled_fabrics,
            force=force,
            vendor=values["VENDOR"],
            project=values["PROJECT_NAME"],
        )


def patch_cmakelists_for_fabric(root: Path, vendor: str, project: str, force: bool) -> None:
    cmake_file = root / "CMakeLists.txt"
    if not cmake_file.exists():
        fail("missing CMakeLists.txt")

    text = cmake_file.read_text(encoding="utf-8")
    original_text = text

    alias_line = f"add_library({vendor}::{project} ALIAS {project})"
    registration_line = 'rhea_register_fabric("${CMAKE_CURRENT_SOURCE_DIR}/fabric.json")'
    fabric_source = f"src/{project}Fabric.cpp"

    changed = False

    # ------------------------------------------------------------------
    # 1) Ensure alias exists
    # ------------------------------------------------------------------
    if alias_line not in text:
        # insert after add_library(project) if possible
        add_library_pattern = re.compile(
            rf'(^\s*add_library\(\s*{re.escape(project)}(?:\s+[^\)]*)?\)\s*$)',
            re.MULTILINE,
        )
        match = add_library_pattern.search(text)
        if match:
            insert_pos = match.end()
            text = text[:insert_pos] + "\n" + alias_line + text[insert_pos:]
        else:
            if not text.endswith("\n"):
                text += "\n"
            text += "\n" + alias_line + "\n"
        changed = True

    # ------------------------------------------------------------------
    # 2) Ensure fabric source is in target_sources(project ...)
    # ------------------------------------------------------------------
    if fabric_source not in text:
        # Try to patch an existing target_sources(project ...)
        target_sources_pattern = re.compile(
            rf'(target_sources\(\s*{re.escape(project)}\s+PRIVATE\s*)(.*?)\)',
            re.DOTALL,
        )
        match = target_sources_pattern.search(text)
        if match:
            prefix = match.group(1)
            body = match.group(2)

            # Preserve indentation style roughly
            if body.strip():
                new_body = body.rstrip() + f'\n    {fabric_source}\n'
            else:
                new_body = f'\n    {fabric_source}\n'

            replacement = prefix + new_body + ")"
            text = text[:match.start()] + replacement + text[match.end():]
            changed = True
        else:
            # No target_sources found for main target; append a small block
            if not text.endswith("\n"):
                text += "\n"
            text += f'\ntarget_sources({project} PRIVATE\n    {fabric_source}\n)\n'
            changed = True

    # ------------------------------------------------------------------
    # 3) Ensure fabric registration line exists
    # ------------------------------------------------------------------
    if registration_line not in text:
        if not text.endswith("\n"):
            text += "\n"
        text += "\n" + registration_line + "\n"
        changed = True

    # ------------------------------------------------------------------
    # Write back if changed
    # ------------------------------------------------------------------
    if changed:
        cmake_file.write_text(text, encoding="utf-8")
        info("updated CMakeLists.txt for fabric support")
    else:
        info("CMakeLists.txt already contains fabric support")

def init_from_template(
    root: Path,
    kind: str,
    features: set[str],
    use_link: bool,
    force: bool,
) -> None:
    vendor, project = detect_vendor_and_project(root)

    script_dir = Path(__file__).resolve().parent
    template_dir = script_dir / "templates" / kind
    if not template_dir.exists():
        fail(f"template directory not found: {template_dir}")

    template_data = load_template_definition(template_dir)
    packages, enabled_fabrics = resolve_template_requirements(template_data, features)

    ensure_packages_installed(root, packages, use_link=use_link)

    values = {
        "PROJECT_NAME": project,
        "PROJECT_NAME_LOWER": project.lower(),
        "PROJECT_NAME_UPPER": project.upper(),
        "VENDOR": vendor,
        "VENDOR_LOWER": vendor.lower(),
        "TARGET_NAME": project,
    }

    write_template_files(
        root=root,
        template_dir=template_dir,
        template_data=template_data,
        values=values,
        enabled_fabrics=enabled_fabrics,
        force=force,
    )

    if kind == "fabric":
        patch_cmakelists_for_fabric(
            root=root,
            vendor=values["VENDOR"],
            project=values["PROJECT_NAME"],
            force=force,
        )

    info(f"initialized Rhea template: {kind}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Rhea project helper")
    parser.add_argument(
        "--project-root",
        default=".",
        help="project root (default: current directory)",
    )

    subparsers = parser.add_subparsers(dest="command", required=True)

    init_parser = subparsers.add_parser("init", help="initialize a Rhea template in an existing mwpkg project")
    init_parser.add_argument("kind", choices=["headless", "client", "fabric"], help="template kind")
    init_parser.add_argument("--with-physics", action="store_true", help="enable the physics feature bundle")
    init_parser.add_argument("--link", action="store_true", help="install packages via 'mwpkg install --link'")
    init_parser.add_argument("--force", action="store_true", help="overwrite generated files if they already exist")

    return parser.parse_args()


def main() -> None:
    args = parse_args()
    root = find_project_root(Path(args.project_root))

    if args.command == "init":
        features: set[str] = set()
        if getattr(args, "with_physics", False):
            features.add("physics")

        init_from_template(
            root=root,
            kind=args.kind,
            features=features,
            use_link=args.link,
            force=args.force,
        )
    else:
        fail(f"unsupported command: {args.command}")


if __name__ == "__main__":
    main()