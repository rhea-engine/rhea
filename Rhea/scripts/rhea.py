#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any


def fail(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def info(msg: str) -> None:
    print(msg)


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def find_project_root(start: Path) -> Path:
    current = start.resolve()
    while True:
        if (current / "CMakeLists.txt").exists():
            return current
        if current.parent == current:
            fail("could not find project root (missing CMakeLists.txt)")
        current = current.parent

def pascal_case(value: str) -> str:
    return "".join(part.capitalize() for part in value.replace("-", "_").split("_"))

def derive_include_prefix(module_id: str | None, name: str | None) -> str:
    if module_id:
        parts = module_id.split("/")
        if len(parts) == 2:
            scope, pkg = parts            
            return f"{pascal_case(scope)}/{pascal_case(pkg)}"

    if name:
        return pascal_case(name)

    fail("could not determine include prefix")

def detect_project_identity(root: Path) -> dict[str, str]:
    module_json = root / "module.json"
    if not module_json.exists():
        fail("missing module.json; run this inside a project created by mwpkg init")

    meta = load_json(module_json)

    module_id = meta.get("id")
    project_name = meta.get("name")
    include_prefix = meta.get("includePrefix")
    author = meta.get("author")

    scope = ""
    package = ""

    if module_id:
        parts = module_id.split("/")
        if len(parts) != 2:
            fail(f"invalid package id '{module_id}', expected '<scope>/<name>'")
        scope, package = parts
        project_name = project_name or package

    if not project_name:
        fail("module.json must contain either 'id' or 'name'")

    include_prefix = include_prefix or derive_include_prefix(module_id, project_name)

    return {
        "MODULE_ID": module_id or "",
        "SCOPE": pascal_case(scope),
        "PROJECT_NAME": pascal_case(project_name),
        "INCLUDE_PREFIX": include_prefix,
        "AUTHOR": author or "",
    }

def render_text(template_text: str, values: dict[str, str]) -> str:
    result = template_text
    for key, value in values.items():
        result = result.replace(f"{{{{{key}}}}}", value)
    return result


def render_path(path_template: str, values: dict[str, str]) -> Path:
    return Path(render_text(path_template, values))


def load_json(path: Path) -> dict[str, Any]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception as e:
        fail(f"failed to parse json file {path}: {e}")
        raise


def load_template_definition(template_dir: Path) -> dict[str, Any]:
    template_json = template_dir / "template.json"
    if not template_json.exists():
        fail(f"missing template definition: {template_json}")
    return load_json(template_json)


def detect_installed_packages_from_mwpkg(root: Path) -> set[str]:
    mwpkg_cmake = root / "mwpkg.cmake"
    if not mwpkg_cmake.exists():
        return set()

    text = mwpkg_cmake.read_text(encoding="utf-8")
    pattern = re.compile(r'add_subdirectory\("mwpkg_installed/([^/"]+)/([^/"]+)"\)')
    packages: set[str] = set()

    for match in pattern.finditer(text):
        vendor, package = match.groups()
        packages.add(f"{vendor}/{package}")

    return packages

def looks_like_default_mwpkg_cmakelists(text: str, project: str) -> bool:
    return (
        f"src/{project}.cpp" in text
        and "rhea_project.cmake" not in text
    )


def looks_like_generated_rhea_cmakelists(text: str) -> bool:
    return "Generated by rhea init" in text or "rhea_project.cmake" in text


def looks_like_default_project_cpp(text: str, include_prefix: str, project: str) -> bool:
    stripped = text.strip()
    expected_include = f'#include <{include_prefix}/{project}.h>'

    if stripped == expected_include:
        return True

    if "Generated by rhea init" in stripped:
        return True

    # Very small placeholder source file
    nonempty_lines = [line.strip() for line in text.splitlines() if line.strip()]
    if len(nonempty_lines) <= 3 and any(expected_include in line for line in nonempty_lines):
        return True

    return False

def looks_like_generated_header(text: str, include_prefix: str, project: str) -> bool:
    stripped = text.strip()

    if "Generated by rhea init" in stripped:
        return True

    expected_include = f"#include <{include_prefix}/{project}.h>"
    if expected_include in stripped:
        return True

    lines = [line.strip() for line in text.splitlines() if line.strip()]
    if len(lines) != 1:
        return False

    line = lines[0]

    if not line.startswith("//"):
        return False

    if not line.endswith("public interface"):
        return False

    return True


def looks_like_generated_enabled_json(text: str) -> bool:
    stripped = text.strip()
    if not stripped:
        return True
    if stripped == "{}":
        return True
    if '"enabled_fabrics"' in stripped and "_generated_by" in stripped:
        return True
    return False


def is_safe_to_overwrite(path: Path, force: bool, include_prefix: str, project: str) -> bool:
    if force:
        return True

    if not path.exists():
        return True

    text = path.read_text(encoding="utf-8")

    if path.name == "CMakeLists.txt":
        return looks_like_default_mwpkg_cmakelists(text, project) or looks_like_generated_rhea_cmakelists(text)

    if path.name == f"{project}.cpp":
        return looks_like_default_project_cpp(text, include_prefix, project)

    if path.name == f"{project}.h":
        return looks_like_generated_header(text, include_prefix, project)

    if path.name == f"{project}.hpp":
        return looks_like_generated_header(text, include_prefix, project)

    if path.name == "enabled.json":
        return looks_like_generated_enabled_json(text)

    if path.name == ".gitkeep":
        return True

    # Default: do not overwrite unknown existing files unless --force
    return False

def run_command(cmd: list[str], cwd: Path) -> None:
    info("running: " + " ".join(cmd))
    result = subprocess.run(cmd, cwd=str(cwd))
    if result.returncode != 0:
        fail(f"command failed with exit code {result.returncode}: {' '.join(cmd)}")


def ensure_packages_installed(root: Path, packages: list[str], use_link: bool = False) -> None:
    installed = detect_installed_packages_from_mwpkg(root)

    for package in packages:
        if package in installed:
            info(f"package already installed: {package}")
            continue

        cmd = ["mwpkg", "install"]
        if use_link:
            cmd.append("--link")
        cmd.append(package)
        run_command(cmd, root)


def resolve_template_requirements(template_data: dict[str, Any], enabled_features: set[str]) -> tuple[list[str], list[str]]:
    packages = list(template_data.get("required_packages", []))
    fabrics = list(template_data.get("default_enabled_fabrics", []))

    features = template_data.get("features", {})
    for feature_name in enabled_features:
        feature = features.get(feature_name)
        if not feature:
            fail(f"unknown feature '{feature_name}' for template '{template_data.get('name', '<unknown>')}'")
        packages.extend(feature.get("packages", []))
        fabrics.extend(feature.get("enabled_fabrics", []))

    # stable unique order
    packages = list(dict.fromkeys(packages))
    fabrics = list(dict.fromkeys(fabrics))
    return packages, fabrics


def check_overwrite_allowed(path: Path, force: bool, include_prefix: str, project: str) -> None:
    if not is_safe_to_overwrite(path, force, include_prefix, project):
        fail(f"{path} already exists and appears user-modified; use --force to overwrite")


def should_ignore_template_path(rel_path: Path) -> bool:
    parts = rel_path.parts
    if not parts:
        return False

    # Skip template metadata and common junk
    if rel_path.name == "template.json":
        return True
    if rel_path.name in {".DS_Store"}:
        return True
    if "__pycache__" in parts:
        return True

    return False


def copy_or_render_template_file(
    src: Path,
    dst: Path,
    values: dict[str, str],
    enabled_fabrics: list[str],
    force: bool,
    include_prefix: str,
    project: str,
    *,
    render: bool | None = None,
) -> None:
    check_overwrite_allowed(dst, force, include_prefix, project)

    ensure_dir(dst.parent)

    should_render = src.suffix == ".in" if render is None else render

    if should_render:
        if src.name == "enabled.json.in":
            rendered = json.dumps(
                {
                    "_generated_by": "rhea init",
                    "enabled_fabrics": enabled_fabrics,
                },
                indent=2,
            ) + "\n"
        else:
            text = src.read_text(encoding="utf-8")
            rendered = render_text(text, values)

            # Add a generated marker comment for known text files
            if dst.suffix in {".cpp", ".h", ".hpp", ".cmake", ".txt"} or dst.name == "CMakeLists.txt":
                rendered = (
                    f"# Generated by rhea init\n\n{rendered}"
                    if dst.name == "CMakeLists.txt"
                    else f"// Generated by rhea init\n\n{rendered}"
                )

        dst.write_text(rendered, encoding="utf-8")
    else:
        shutil.copyfile(src, dst)

    info(f"wrote {dst}")


def write_template_files(
    root: Path,
    template_dir: Path,
    template_data: dict[str, Any],
    values: dict[str, str],
    enabled_fabrics: list[str],
    force: bool,
) -> None:
    file_entries = template_data.get("files", [])
    if not isinstance(file_entries, list):
        fail("'files' in template.json must be a list")

    explicitly_handled_sources: set[Path] = set()

    # 1) Handle explicitly declared files first.
    for file_entry in file_entries:
        src_rel = Path(file_entry["source"])
        dst_rel = render_path(file_entry["target"], values)
        render = file_entry["render"]

        src = template_dir / src_rel
        if not src.exists():
            fail(f"missing template file: {src}")

        explicitly_handled_sources.add(src_rel)

        dst = root / dst_rel
        copy_or_render_template_file(
            src=src,
            dst=dst,
            values=values,
            enabled_fabrics=enabled_fabrics,
            force=force,
            include_prefix=values["INCLUDE_PREFIX"],
            project=values["PROJECT_NAME"],
            render=render,
        )

    # 2) Copy all remaining template files recursively by default.
    for src in template_dir.rglob("*"):
        if src.is_dir():
            continue

        rel = src.relative_to(template_dir)

        if should_ignore_template_path(rel):
            continue

        if rel in explicitly_handled_sources:
            continue

        dst = root / rel
        copy_or_render_template_file(
            src=src,
            dst=dst,
            values=values,
            enabled_fabrics=enabled_fabrics,
            force=force,
            include_prefix=values["INCLUDE_PREFIX"],
            project=values["PROJECT_NAME"],
            render=None,  # default behavior: render .in files, copy others
        )


def init_from_template(
    root: Path,
    kind: str,
    features: set[str],
    use_link: bool,
    force: bool,
) -> None:
    identity = detect_project_identity(root)
    project = identity["PROJECT_NAME"]
    scope = identity["SCOPE"]
    include_prefix = identity["INCLUDE_PREFIX"]
    module_id = identity["MODULE_ID"]
    author = identity["AUTHOR"]

    script_dir = Path(__file__).resolve().parent
    template_dir = script_dir / "templates" / kind
    if not template_dir.exists():
        fail(f"template directory not found: {template_dir}")

    template_data = load_template_definition(template_dir)
    packages, enabled_fabrics = resolve_template_requirements(template_data, features)

    ensure_packages_installed(root, packages, use_link=use_link)

    values = {
        "MODULE_ID": module_id,
        "SCOPE": scope,
        "SCOPE_LOWER": scope.lower(),
        "PROJECT_NAME": project,
        "PROJECT_NAME_LOWER": project.lower(),
        "PROJECT_NAME_UPPER": project.upper(),
        "INCLUDE_PREFIX": include_prefix,
        "TARGET_NAME": scope + project,
        "AUTHOR": author or "",
    }

    write_template_files(
        root=root,
        template_dir=template_dir,
        template_data=template_data,
        values=values,
        enabled_fabrics=enabled_fabrics,
        force=force,
    )

    info(f"initialized Rhea template: {kind}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Rhea project helper")
    parser.add_argument(
        "--project-root",
        default=".",
        help="project root (default: current directory)",
    )

    subparsers = parser.add_subparsers(dest="command", required=True)

    init_parser = subparsers.add_parser("init", help="initialize a Rhea template in an existing mwpkg project")
    init_parser.add_argument("kind", choices=["headless", "client", "fabric"], help="template kind")
    init_parser.add_argument("--with-physics", action="store_true", help="enable the physics feature bundle")
    init_parser.add_argument("--link", action="store_true", help="install packages via 'mwpkg install --link'")
    init_parser.add_argument("--force", action="store_true", help="overwrite generated files if they already exist")

    return parser.parse_args()


def main() -> None:
    args = parse_args()
    root = find_project_root(Path(args.project_root))

    if args.command == "init":
        features: set[str] = set()
        if getattr(args, "with_physics", False):
            features.add("physics")

        init_from_template(
            root=root,
            kind=args.kind,
            features=features,
            use_link=args.link,
            force=args.force,
        )
    else:
        fail(f"unsupported command: {args.command}")


if __name__ == "__main__":
    main()